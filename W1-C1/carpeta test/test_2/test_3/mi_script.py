# Un programa sencillo para sumar dos números
def sumar(a, b):
    return a + b

# Entrada del usuario
num1 = float(input("Ingresa el primer número: "))
num2 = float(input("Ingresa el segundo número: "))

# Muestra el resultado
print(f"La suma de {num1} y {num2} es {sumar(num1, num2)}")